interface LegalIconProps {
  name?: string;
  className?: string;
  fallback?: LucideIcon;
}

export function LegalIcon({
  name,
  className = "w-4 h-4",
  fallback = FileText,
}: LegalIconProps) {
  const IconComponent = (name && LEGAL_ICON_MAP[name]) || fallback;
  return <IconComponent className={className} />;
}

